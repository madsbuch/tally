type SyncState<'a> = tauri::State<'a, std::sync::Arc<sync::service::SyncService>>;

/// Starts sync once the frontend has loaded (and so migrated) the database.
#[tauri::command]
async fn sync_start(app: tauri::AppHandle, svc: SyncState<'_>) -> Result<(), String> {
    let pool = db_pool(&app).await?;
    use tauri_plugin_sync_background::SyncBackgroundExt;
    // mDNS needs multicast, which Android only delivers under a lock.
    if let Err(e) = app.sync_background().hold_multicast_lock() {
        eprintln!("sync: couldn't take the multicast lock: {e}");
    }
    svc.start(app.clone(), pool).await?;
    // Android also syncs with the app closed, every half hour on Wi-Fi.
    if let Ok(dir) = app.path().app_config_dir() {
        let db_path = dir.join("tally.db").to_string_lossy().into_owned();
        if let Err(e) = app
            .sync_background()
            .schedule(tauri_plugin_sync_background::ScheduleArgs { db_path })
        {
            eprintln!("sync: couldn't schedule background sync: {e}");
        }
    }
    Ok(())
}

/// Before anything is written to a freshly opened database: a copy of it
/// from elsewhere (restored, put back) takes a new device id (instance.rs).
#[tauri::command]
async fn sync_check_instance(app: tauri::AppHandle) -> Result<(), String> {
    let pool = db_pool(&app).await?;
    let dir = app.path().app_config_dir().map_err(|e| e.to_string())?;
    match sync::instance::check(&pool, &dir.join("tally.db")).await? {
        sync::instance::Check::Rotated { old_id, new_id } => {
            eprintln!("sync: this database was a copy from elsewhere; device {old_id} is now {new_id}");
        }
        _ => {}
    }
    Ok(())
}

/// Marks an exported copy of the database as a copy (instance.rs).
#[tauri::command]
async fn mark_db_copy(path: String) -> Result<(), String> {
    sync::instance::mark_copy(std::path::Path::new(&path)).await
}

