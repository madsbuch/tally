/// Photos live in the `photos` table of the app database (see
/// `src/db/schema.ts`). The photo commands bind the bytes as a real BLOB through
/// the SQL plugin's own sqlx pool — the plugin's JS API can only pass JSON
/// values, which would turn every image into an array of numbers.
async fn db_pool(app: &tauri::AppHandle) -> Result<sqlx::SqlitePool, String> {
    let instances = app.state::<DbInstances>();
    let instances = instances.0.read().await;
    match instances.get(DB_URL) {
        Some(DbPool::Sqlite(pool)) => Ok(pool.clone()),
        // The frontend loads the DB (and runs migrations) before touching
        // photos; reaching this means it didn't.
        _ => Err("database not loaded".into()),
    }
}

/// Where photos were kept as loose files before they moved into the
/// database. Only read by `import_photo_files`.
fn legacy_photos_dir(app: &tauri::AppHandle) -> Result<std::path::PathBuf, String> {
    Ok(app
        .path()
        .app_data_dir()
        .map_err(|e| e.to_string())?
        .join("photos"))
}

/// Stores a base64-encoded JPEG and returns the filename it's keyed by.
#[tauri::command]
async fn save_photo(app: tauri::AppHandle, data_base64: String) -> Result<String, String> {
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(data_base64.as_bytes())
        .map_err(|e| e.to_string())?;
    photos::save(&db_pool(&app).await?, &bytes).await
}

/// Reads a stored photo back as base64. (The WebView can't fetch it any other
/// way: it isn't a file, and CSP blocks connect-src on Android anyway.)
#[tauri::command]
async fn read_photo(app: tauri::AppHandle, filename: String) -> Result<String, String> {
    let data = photos::read(&db_pool(&app).await?, &filename).await?;
    Ok(base64::engine::general_purpose::STANDARD.encode(data))
}

#[tauri::command]
async fn delete_photo(app: tauri::AppHandle, filename: String) -> Result<(), String> {
    photos::delete(&db_pool(&app).await?, &filename).await
}

/// Stores a library document's original file (base64), e.g. the PDF its page
/// images were rendered from (see `document_files`).
#[tauri::command]
async fn save_document_file(
    app: tauri::AppHandle,
    document_id: String,
    filename: String,
    media_type: String,
    data_base64: String,
) -> Result<(), String> {
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(data_base64.as_bytes())
        .map_err(|e| e.to_string())?;
    document_files::save(&db_pool(&app).await?, &document_id, &filename, &media_type, &bytes).await
}

/// Reads a library document's original file back as base64.
#[tauri::command]
async fn read_document_file(app: tauri::AppHandle, document_id: String) -> Result<String, String> {
    let data = document_files::read(&db_pool(&app).await?, &document_id).await?;
    Ok(base64::engine::general_purpose::STANDARD.encode(data))
}

/// Moves photos left as loose files from before they lived in the database
/// into it (see `photos::import_files`).
#[tauri::command]
async fn import_photo_files(app: tauri::AppHandle) -> Result<u32, String> {
    let dir = legacy_photos_dir(&app)?;
    if !dir.exists() {
        return Ok(0);
    }
    photos::import_files(&db_pool(&app).await?, &dir).await
}

/// Prepares a destination path for a database export: clears old exports and
/// returns the absolute path the frontend should `VACUUM INTO` (the snapshot
/// itself must be written by SQLite for consistency with the live WAL).
#[tauri::command]
fn prepare_db_export(app: tauri::AppHandle, file_name: String) -> Result<String, String> {
    if file_name.contains('/') || file_name.contains('\\') || file_name.contains("..") {
        return Err("invalid file name".into());
    }
    let dir = app
        .path()
        .app_data_dir()
        .map_err(|e| e.to_string())?
        .join("exports");
    // VACUUM INTO refuses to overwrite; start from an empty dir.
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    Ok(dir.join(file_name).to_string_lossy().into_owned())
}

