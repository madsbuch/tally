#[tauri::command]
async fn sync_check(svc: SyncState<'_>) -> Result<sync::service::ConnectionCheck, String> {
    svc.check().await
}

/// Opens the setting that lets Tally onto the local network (macOS).
#[tauri::command]
fn sync_open_network_settings() -> Result<(), String> {
    #[cfg(target_os = "macos")]
    {
        std::process::Command::new("open")
            .arg(sync::reach::NETWORK_SETTINGS_URL)
            .spawn()
            .map_err(|e| e.to_string())?;
    }
    Ok(())
}

#[tauri::command]
fn sync_now(svc: SyncState<'_>) {
    svc.kick();
}

#[tauri::command]
async fn sync_remove_device(svc: SyncState<'_>, id: String) -> Result<(), String> {
    sync::service::remove_device(svc.pool()?, &id).await?;
    svc.kick();
    Ok(())
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = tauri::Builder::default();
    // Scanning the pairing QR code (the computer uses its webcam from JS).
    #[cfg(mobile)]
    let builder = builder.plugin(tauri_plugin_barcode_scanner::init());
    builder
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_http::init())
        .plugin(tauri_plugin_notification::init())
        .plugin(
            tauri_plugin_sql::Builder::default()
                .add_migrations(DB_URL, migrations())
                .build(),
        )
        .plugin(tauri_plugin_background::init())
        .plugin(tauri_plugin_coach::init())
        .plugin(tauri_plugin_fasting::init())
        .plugin(tauri_plugin_health_connect::init())
        .plugin(tauri_plugin_share::init())
        .plugin(tauri_plugin_sync_background::init())
        .manage(std::sync::Arc::new(sync::service::SyncService::default()))
        .manage(garmin::GarminState::new())
        .setup(|app| {
            // A development build never runs as the real app: it would open
            // the real database, and with sync, whatever unfinished code does
            // to it would reach every device. `bun run tauri dev` runs it as
            // "Tally Dev" (scripts/tauri.mjs); anything else is stopped here.
            #[cfg(all(debug_assertions, desktop))]
            if app.config().identifier == PRODUCTION_IDENTIFIER {
                eprintln!(
                    "\nThis is a development build running as the real Tally ({PRODUCTION_IDENTIFIER}),\n\
                     which would open your real database. Start it with `bun run tauri dev`,\n\
                     which runs it as \"Tally Dev\" with its own data.\n"
                );
                std::process::exit(1);
            }

            // Before the SQL plugin migrates (that happens when the frontend
            // first loads the database), keep a copy of the database as it was.
            // tauri-plugin-sql resolves `sqlite:tally.db` in app_config_dir.
            if let Ok(dir) = app.path().app_config_dir() {
                let db = dir.join("tally.db");
                for (version, name) in [
                    (UUID_IDS_VERSION, "tally-before-uuid-ids.db"),
                    (TYPE_IDS_VERSION, "tally-before-type-ids.db"),
                ] {
                    let copy = dir.join(name);
                    match tauri::async_runtime::block_on(backup::before_migration(&db, version, &copy)) {
                        Ok(true) => eprintln!("Backed up the database to {}", copy.display()),
                        Ok(false) => {}
                        Err(e) => eprintln!("Could not back up the database before migrating: {e}"),
                    }
                }
            }
            Ok(())
        })
        .invoke_handler(tauri::generate_handler![
            save_photo,
            read_photo,
            delete_photo,
            import_photo_files,
            save_document_file,
            read_document_file,
            prepare_db_export,
            sync_start,
            sync_check_instance,
            mark_db_copy,
            sync_status,
            sync_set_name,
            sync_offer,
            sync_cancel_offer,
            sync_join,
            sync_now,
            sync_check,
            sync_open_network_settings,
            sync_remove_device,
            garmin::garmin_status,
            garmin::garmin_set_key,
            garmin::garmin_clear_key,
            garmin::garmin_login,
            garmin::garmin_mfa,
            garmin::garmin_logout,
            garmin::garmin_get,
            garmin::garmin_activity_laps
        ])
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
